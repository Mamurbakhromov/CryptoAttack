export function getCoinClassification(symbol: string | null | undefined): CoinClassification {
  const normalized = normalizeCoinSymbol(symbol);
  if (!normalized) return 'unknown';
  if (haramCoinSymbols.has(normalized)) return 'haram';
  if (doubtfulCoinSymbols.has(normalized)) return 'doubtful';
  if (halalCoinSymbols.has(normalized)) return 'halal';
  return 'unknown';
}

export function getCryptoIslamClassification(symbol: string | null | undefined): CoinClassification {
  const normalized = normalizeCoinSymbol(symbol);
  if (!normalized) return 'unknown';
  if (cryptoIslamHaramCoinSymbols.has(normalized)) return 'haram';
  if (cryptoIslamDoubtfulCoinSymbols.has(normalized)) return 'doubtful';
  if (cryptoIslamHalalCoinSymbols.has(normalized)) return 'halal';
  return 'unknown';
}

export function getCoinClassificationClasses(symbol: string | null | undefined): string {
  return `crypto-halal-${getCoinClassification(symbol)} crypto-islam-${getCryptoIslamClassification(symbol)}`;
}

export function isHalalCoin(symbol: string | null | undefined): boolean {
  return getCoinClassification(symbol) === 'halal';
}

export function isHalalByAnySource(symbol: string | null | undefined): boolean {
  return getCoinClassification(symbol) === 'halal' || getCryptoIslamClassification(symbol) === 'halal';
}

export function isCoinClassificationFilterActive(filter: CoinClassificationFilter): boolean {
  return filter.length > 0;
}

export function getCoinClassificationFilterLabel(filter: CoinClassificationFilter): string {
  if (!filter.length) return 'All coins';
  const labels = filter.map((mode) => coinClassificationFilterOptions.find((option) => option.value === mode)?.label ?? mode);
  return labels.join(', ');
}

export function matchesCoinClassificationFilter(symbol: string | null | undefined, filter: CoinClassificationFilter): boolean {
  if (!filter.length) return true;

  const cryptoHalalStatus = getCoinClassification(symbol);
  const cryptoIslamStatus = getCryptoIslamClassification(symbol);

  return filter.some((mode) => {
    if (mode === 'halal') {
      return (cryptoHalalStatus === 'halal' || cryptoIslamStatus === 'halal')
        && cryptoHalalStatus !== 'haram'
        && cryptoHalalStatus !== 'doubtful'
        && cryptoIslamStatus !== 'haram'
        && cryptoIslamStatus !== 'doubtful';
    }
    if (mode === 'either_halal') return cryptoHalalStatus === 'halal' || cryptoIslamStatus === 'halal';
    if (mode === 'haram') return cryptoHalalStatus === 'haram' || cryptoIslamStatus === 'haram';
    return cryptoHalalStatus === 'unknown' && cryptoIslamStatus === 'unknown';
  });
}

function normalizeCoinSymbol(symbol: string | null | undefined): string {
  return (symbol ?? '').trim().toUpperCase().replace(/^[#$]+/, '').replace(/[^A-Z0-9]/g, '');
}
